    inc = base_win[s][0] > 1
    def state(f):
        y, N = y0.copy(), N0.copy(); r = f * y[j]; y[j] -= r; N[j] -= r; return win_fit_counts(y, N)
    def crosses(f):
        OR, lo, hi = state(f); return (lo <= 1) if inc else (hi >= 1)
    def flips(f):
        OR = state(f)[0]; return (OR <= 1) if inc else (OR >= 1)
    def search(pred):
        """first f on a 0.001 grid where pred holds (fits near f=1 can separate, so scan upward), refined by bisection"""
        grid = np.round(np.arange(0, 0.999, 0.001), 3); prev = 0.0
        for f in grid:
            try: ok = bool(pred(f))
            except Exception: ok = False
            if ok:
                if f == 0: return 0.0
                a, b = prev, f
                for _ in range(30):
                    mid = (a + b) / 2; (b := mid) if pred(mid) else (a := mid)
                return b
            prev = f
        return np.nan
