# ── P4b tipping point: share f of the series' own repositories in the trend-supporting end year (2025 for increases,
#    2023 for decreases) that would have to be false positives, with none elsewhere, for the 2023-2025 CI to include 1
def win_fit_counts(y, N):
    t = np.arange(2023, 2026) - 2016; m = sm.GLM(np.column_stack([y, N - y]), sm.add_constant(t), family=sm.families.Binomial()).fit()
    lo, hi = np.exp(m.conf_int()[1]); return np.exp(m.params[1]), lo, hi
