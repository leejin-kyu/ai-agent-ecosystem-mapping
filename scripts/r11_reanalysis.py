def counts(d, col, years):
    g = d.groupby('year').agg(N=(col, 'size'), y=(col, 'sum')).reindex(years).fillna(0); return g
def loglin(d, col, window=None):
    years = np.arange(2016, 2026) if window is None else np.arange(window[0], window[1] + 1)
    dd = d if window is None else d[d['year'].between(*window)]
    g = counts(dd, col, years); g = g[g['N'] > 0]
    m = sm.GLM(np.column_stack([g['y'], g['N'] - g['y']]), sm.add_constant(g.index.values - 2016), family=sm.families.Binomial()).fit()
    lo, hi = np.exp(m.conf_int()[1]); return np.exp(m.params[1]), lo, hi, m.pvalues[1]
def segmented(d, col):
    g = counts(d, col, np.arange(2016, 2026)); t = g.index.values - 2016
    X = np.column_stack([np.ones(len(t)), t, np.clip(t - 7, 0, None)])
    m = sm.GLM(np.column_stack([g['y'], g['N'] - g['y']]), X, family=sm.families.Binomial()).fit()
    b = m.params[1] + m.params[2]; cv = m.cov_params(); se = np.sqrt(cv[1, 1] + cv[2, 2] + 2 * cv[1, 2]); p = 2 * (1 - stats.norm.cdf(abs(b / se)))
    return np.exp(b), np.exp(b - 1.96 * se), np.exp(b + 1.96 * se), p
def spline_lr(d, col):
    g = counts(d, col, np.arange(2016, 2026)).reset_index(); g['t'] = g['year'] - 2016; e = np.column_stack([g['y'], g['N'] - g['y']])
    m1 = sm.GLM(e, sm.add_constant(g['t']), family=sm.families.Binomial()).fit()
    Xs = patsy.dmatrix('cr(t, df=3)', g, return_type='dataframe'); m2 = sm.GLM(e, Xs, family=sm.families.Binomial()).fit()
    return 1 - stats.chi2.cdf(2 * (m2.llf - m1.llf), Xs.shape[1] - 2)
def quarterly(d, col):
    q = d[d['year'] >= 2023].groupby('quarter').agg(N=(col, 'size'), y=(col, 'sum')).reset_index(); t = np.arange(len(q)) / 4.0
    m = sm.GLM(np.column_stack([q['y'], q['N'] - q['y']]), sm.add_constant(t), family=sm.families.Binomial()).fit()
    lo, hi = np.exp(m.conf_int()[1]); return np.exp(m.params[1]), lo, hi, m.pvalues[1]

